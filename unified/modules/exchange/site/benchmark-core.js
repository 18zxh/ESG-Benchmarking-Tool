import {DIMENSIONS,ProjectStore,safeDraft} from './workbench-core.js';
export const cellKey=(topicId,checkId)=>topicId+'::'+checkId;
export function benchmarkRows(rules,framework){
 return rules.topics.flatMap(topic=>framework.levels.flatMap(level=>level.checks.map(check=>({key:cellKey(topic.id,check.id),topicId:topic.id,topicName:topic.name,dimension:topic.dimension,dimensionName:DIMENSIONS[topic.dimension],levelId:level.id,levelName:level.name,...check}))));
}
export function newBenchmark(rules,framework){return {id:crypto.randomUUID(),name:'',industry:'',targetReportId:'',reports:[],rules:structuredClone(rules),framework:structuredClone(framework)};}
export function coverage(project,key){
 const peers=project.reports.filter(r=>r.id!==project.targetReportId);
 const completed=peers.filter(r=>r.results?.[key]?.status==='completed'&&['Yes','N'].includes(r.results[key].value));
 const yes=completed.filter(r=>r.results[key].value==='Yes').length;
 return {yes,completed:completed.length,total:peers.length,rate:completed.length?yes/completed.length:null};
}
export function validateBenchmark(project){
 if(!project.name.trim())throw new Error('请填写对标项目名称。');
 if(!project.reports.length)throw new Error('请先上传公司ESG报告。');
 const identities=new Set();
 for(const r of project.reports){
  if(!r.companyName.trim()||!/^\d{4}$/.test(r.reportYear))throw new Error('请为每份报告填写公司名称和四位报告覆盖年度。');
  const identity=r.companyName.trim().toLocaleLowerCase();
  if(identities.has(identity))throw new Error('同一公司只能有一份报告参与覆盖率，请选择需要比较的覆盖年度。');
  identities.add(identity);
  if(!r.meta?.runtimeReady)throw new Error('部分原报告尚未就绪，请重新上传或恢复草稿。');
 }
}
export class BenchmarkStore extends ProjectStore{
 constructor(factory=globalThis.indexedDB,name='exchange-peer-benchmark'){super(factory,name);}
 async save(project){const value=safeDraft(project);value.storageKey=project.id;value.savedAt=new Date().toISOString();await this.run('readwrite',s=>s.put(value));return value;}
}
export function benchmarkSheets(project){
 const reports=project.reports,rows=benchmarkRows(project.rules,project.framework),columns=reports.map(r=>r.companyName+' · '+r.reportYear+(r.id===project.targetReportId?'（本公司）':''));
 const matrix=[['类别','议题','一级','二级',...columns,'同业覆盖率','披露同业数','已核对同业数','同业总数']];
 const evidence=[['公司','报告覆盖年度','议题','一级','二级','判断','依据','文件','PDF物理页','原文']];
 for(const row of rows){
  const c=coverage(project,row.key);
  matrix.push([row.dimensionName,row.topicName,row.levelName,row.name,...reports.map(r=>r.results?.[row.key]?.status==='completed'?r.results[row.key].value:''),c.rate,c.yes,c.completed,c.total]);
  for(const r of reports){
   const result=r.results?.[row.key];if(!result)continue;
   const base=[r.companyName,r.reportYear,row.topicName,row.levelName,row.name,result.status==='completed'?result.value:'未完成',result.reason||''];
   if(result.evidence?.length)for(const e of result.evidence)evidence.push([...base,e.name,e.page,e.quote]);else evidence.push([...base,'','','']);
  }
 }
 const mappings=[['公司','报告覆盖年度','报告原章节','统一议题','PDF物理页','映射方式']];
 for(const r of reports)for(const m of r.mappings||[])mappings.push([r.companyName,r.reportYear,m.reportSection,project.rules.topics.find(t=>t.id===m.topicId)?.name||m.topicId,m.sourcePage.join('、'),m.autoGenerated===false?'人工修正':'自动映射']);
 const notes=[['项目','内容'],['名称',project.name],['行业',project.industry],['对标框架版本',project.framework.version],['规则集版本',project.rules.version],
 ['覆盖率口径','每行Yes同业数／该行已完成核对的同业数；本公司不计入。空白及失败不计作N，完成数与总数同时列示。覆盖率以百分比显示，底层为0至1数值。'],
 ['判断口径','Yes须有对应披露及原文证据；N为完整读取后未发现。仅有标题或映射成功不直接构成Yes。'],
 ['框架来源',project.framework.source],...reports.map(r=>[r.companyName+' · '+r.reportYear,r.meta.name+' · '+r.meta.sha256+' · '+(r.status||'未处理')])];
 return [{name:'同一议题对标',rows:matrix,freezeRows:1,percentColumns:[4+reports.length],wrap:true},{name:'判断与原文证据',rows:evidence,freezeRows:1,wrap:true},{name:'议题映射',rows:mappings,freezeRows:1,wrap:true},{name:'项目与口径',rows:notes,wrap:true}];
}
