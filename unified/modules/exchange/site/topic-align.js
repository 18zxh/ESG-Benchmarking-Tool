import {reviseMapping} from './workbench-core.js';

export function element(doc,tag,text='',className=''){
  const node=doc.createElement(tag);if(text!==null)node.textContent=text;if(className)node.className=className;return node;
}
export function renderMappings(body,mappings,rules,{onChange=()=>{},onPreview=()=>{},locked=false,alignmentComplete=false}={}){
  const doc=body.ownerDocument;body.replaceChildren();
  if(!mappings.length){const row=element(doc,'tr'),cell=element(doc,'td',alignmentComplete?'未找到可对应的章节。自动对齐已完成；无映射的议题将保留待全文核验。':'尚无对齐结果。完成主报告解析并连接服务后，可对齐报告章节。');cell.colSpan=5;row.append(cell);body.append(row);return;}
  const sorted=[...mappings].sort((a,b)=>b.confidence-a.confidence);
  for(const mapping of sorted){
    const row=element(doc,'tr');row.dataset.mappingId=mapping.id;
    const source=element(doc,'td',mapping.reportSection),pages=element(doc,'button',`主报告 · PDF 第 ${mapping.sourcePage.join('、')} 页`);pages.type='button';pages.addEventListener('click',()=>onPreview(mapping.sourcePage[0]));source.append(element(doc,'br'),pages);
    const target=element(doc,'td'),select=element(doc,'select');select.setAttribute('aria-label',`${mapping.reportSection} 对应议题`);select.disabled=locked;
    for(const topic of rules.topics){const option=element(doc,'option',topic.name);option.value=topic.id;select.append(option);}select.value=mapping.topicId;
    select.addEventListener('change',()=>onChange(mapping.id,reviseMapping(mapping,rules.topics.find(t=>t.id===select.value))));target.append(select,element(doc,'small',mapping.clause));
    const confidence=element(doc,'td',`${Math.round(mapping.confidence*100)}%`);confidence.className='numeric';
    const state=element(doc,'td',mapping.autoGenerated?'自动对齐':'已修正');
    if(mapping.trace?.length)state.append(element(doc,'small',`修正记录 ${mapping.trace.length} 次`));
    const actions=element(doc,'td'),undo=element(doc,'button','撤销修正');undo.type='button';undo.disabled=locked||!mapping.original||mapping.autoGenerated;
    undo.addEventListener('click',()=>onChange(mapping.id,reviseMapping(mapping,{},'undo')));actions.append(undo);row.append(source,target,confidence,state,actions);body.append(row);
  }
}
