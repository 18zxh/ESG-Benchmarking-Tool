export function rebindDocument(project,source,meta){
  project.reports[source]=meta;
  for(const topic of project.topics)for(const assessment of [topic.assessment,...(topic.history||[]).map(h=>h.assessment)].filter(Boolean)){
    for(const e of assessment.evidence||[])if(e.source===source){e.documentId=meta.id;e.name=meta.name;}
    assessment.reportSource=[...new Set((assessment.evidence||[]).map(e=>`${e.name} · PDF 第 ${e.page} 页`))].join('；');
  }
}
export function sectionSource(project,topicId){return [...new Set(project.topicMappings.filter(m=>m.topicId===topicId).map(m=>m.reportSection))].join('；');}
export function mergeResults(project,job){
  for(const [topicId,result] of Object.entries(job.results||{})){
    const state=project.topics.find(t=>t.topicId===topicId);if(!state)continue;
    const identity=[job.id,JSON.stringify(result)].join(':');if(state.lastResultIdentity===identity)continue;
    if(state.assessment){state.history??=[];state.history.push({assessment:clone(state.assessment),status:state.status,at:new Date().toISOString(),reason:'重新初评前的结果'});}
    state.status=result.status;state.assessment=result.assessment?clone(result.assessment):undefined;state.error=result.error?clone(result.error):undefined;state.lastResultIdentity=identity;
  }
  project.reviewUsage=clone(job.usage);project.readingMode=job.mode;project.lastTaskId=job.id;
  if(job.readingVersion)project.readingVersion=job.readingVersion;if(job.assessmentVersion)project.assessmentVersion=job.assessmentVersion;
  if(job.status==='completed')project.status='已初评';else if(job.status==='in_progress')project.status='初评中';
  return project;
}
