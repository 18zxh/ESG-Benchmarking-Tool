export function applyRules(project,rules) {
  project.exchange=rules.exchange;project.rulesetVersion=rules.version;project.ruleSnapshot=clone(rules);
  project.topics=rules.topics.map(t=>({topicId:t.id,selected:t.governanceDefault,status:'pending',comment:'',history:[]}));
  project.topicMappings=[];project.alignmentComplete=false;project.alignedAt=null;
  delete project.assessmentContext;project.contextMismatch=false;
  project.status='已配置';return project;
}
export function validateProject(project,rules) {
  if(!project.customerName.trim())throw new Error('请填写客户名称。');
  if(!/^\d{4}$/.test(project.reportYear)||!/^\d{4}$/.test(project.targetYear))throw new Error('请填写四位报告覆盖年度和目标披露年度。');
  if(!rules||rules.exchange!==project.exchange)throw new Error('请选择交易所。');
  if(rules.boardOptions.length&&!rules.boardOptions.includes(project.board))throw new Error('请选择该交易所的板块。');
  if(project.exchange==='hk'){
    if(!['largecap','mainboard','gem'].includes(project.issuerCategory))throw new Error('请选择港交所发行人类别。');
    const date=project.fiscalYearStart||'';if(!/^\d{4}-\d{2}-\d{2}$/.test(date)||Number.isNaN(Date.parse(date))||new Date(date).toISOString().slice(0,10)!==date||date<'2025-01-01')throw new Error('请选择2025年1月1日或之后的有效财政年度开始日期。');
    if(project.board!==(project.issuerCategory==='gem'?'GEM':'主板'))throw new Error('发行人类别与上市板块不一致。');
  }
  return true;
}
export function projectIdentity(project) {
  return JSON.stringify([project.id,project.customerName,project.reportYear,project.targetYear,project.exchange,project.board,
    ...(project.exchange==='hk'?[project.issuerCategory,project.fiscalYearStart]:[]),project.reports.main?.sha256||'',project.reports.annual?.sha256||'',project.rulesetVersion]);
}
export function reviseMapping(mapping,topic,action='change') {
  const next=clone(mapping),time=new Date().toISOString();
  next.trace=[...(next.trace||[]),{action,at:time,from:next.topicId,to:action==='undo'?(next.original?.topicId||next.topicId):topic.id}];
  if(action==='undo') {
    if(next.original){const trace=next.trace;Object.assign(next,clone(next.original));next.trace=trace;}
    return next;
  }
  if(!next.original){const original=clone(next);delete original.trace;next.original=original;}
  Object.assign(next,{topicId:topic.id,topicName:topic.name,clause:topic.clause,autoGenerated:false,confirmed:true,correctedAt:time});
  return next;
}
