export function sourceLink(file, page = 1, label = '查看官方 PDF') {
  return `<a target="_blank" rel="noopener" href="sources/${encodeURIComponent(file)}#page=${Number(page) || 1}">${esc(label)} · 第 ${Number(page) || 1} 页</a>`;
}
export function effectiveDisclosure(q, listed) {
  return q.disclosure === 'Flexible'
    ? listed === 'listed'
      ? 'Public'
      : listed === 'nonlisted'
        ? 'Flexible'
        : '待核实'
    : q.disclosure;
}

